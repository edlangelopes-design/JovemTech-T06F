function somar(numero1, numero2) {
  let resultado = numero1 + numero2;
  return resultado; // Devolve o valor e sai da função
}

// Guardando o resultado da função dentro de uma variável
let total = somar(5, 3); 
console.log(total); // Saída: 8

// Usando o retorno diretamente
console.log(somar(10, 20)); // Saída: 30
